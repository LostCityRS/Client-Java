package jagex3.dash3d;

import deob.ObfuscatedName;

@ObfuscatedName("kb")
public final class PointNormal {

	@ObfuscatedName("kb.k")
	public int z;

	@ObfuscatedName("kb.o")
	public int w;

	@ObfuscatedName("kb.u")
	public int y;

	@ObfuscatedName("kb.w")
	public int x;

	public PointNormal() {
	}

	public PointNormal(PointNormal arg0) {
		this.z = arg0.z;
		this.y = arg0.y;
		this.x = arg0.x;
		this.w = arg0.w;
	}
}
