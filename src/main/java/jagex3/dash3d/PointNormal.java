package jagex3.dash3d;

import deob.ObfuscatedName;

@ObfuscatedName("ie")
public final class PointNormal {

	@ObfuscatedName("ie.b")
	public int y;

	@ObfuscatedName("ie.c")
	public int z;

	@ObfuscatedName("ie.d")
	public int w;

	@ObfuscatedName("ie.e")
	public int x;

	public PointNormal() {
	}

	public PointNormal(PointNormal arg0) {
		this.z = arg0.z;
		this.y = arg0.y;
		this.x = arg0.x;
		this.w = arg0.w;
	}
}
